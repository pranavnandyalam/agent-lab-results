"""Referee-round-2 post-hoc numbers (exploratory, not pre-registered). numpy only, no model scoring.
Usage: HF_HUB_OFFLINE=1 OMP_NUM_THREADS=4 .venv/bin/python -I src/posthoc2.py [--split test]
Writes results/posthoc_<split>_r2.md. Deterministic: all bootstraps use numpy default_rng(0), 2000 resamples.
Sections:
 1. cot-view AUROC B-vs-A, Bnc-vs-A, K, Acue-vs-A with skeleton-cluster bootstrap CI (analyze.Boot, identical
    weights to analyze.py) + exact cluster sign-flip permutation test for K (swap B/Bnc within instance, one flip
    per skeleton cluster, all 2^12 assignments enumerated).
 2. action-view AUROC(a1 vs a0) pooled / per family, bootstrap over instance pairs stratified by family;
    same after excluding instances whose a1 action text contains a cue stem (cues.CUE_RE).
 3. hack-variant parity breakdown + skeleton/parity alias table.
 4. H4 O = AUROC_action(D vs A) - AUROC_both(D vs A) per family (skeleton bootstrap and instance bootstrap).
"""
import argparse
import itertools
import os
import re
import sys
from collections import Counter

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from analyze import Boot, MONS, NBOOT, ROOT, SEED, auroc, ci, load_instances, load_scores, skel  # noqa: E402
from cues import CUE_RE, find_cues  # noqa: E402

PROMPTS = ["v2", "v1", "v3"]
# monitors analysed per prompt (task spec; other files e.g. a partially written v3 qwen2.5-1.5b are ignored)
MON_OF = {"v2": MONS, "v1": ["qwen2.5-0.5b", "qwen3-0.6b"], "v3": ["qwen2.5-0.5b", "qwen3-0.6b"]}


def parse_posthoc(path):
    """Parse the main per-prompt table of results/posthoc_<split>.md (round-1 output) for point-estimate checks."""
    out, pr = {}, None
    if not os.path.exists(path):
        return out
    for line in open(path):
        mm = re.match(r"## prompt (\w+)", line)
        if mm:
            pr = mm.group(1); continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if pr and len(c) == 8 and c[0] in MONS and c[1].isdigit():
            out[(pr, c[0])] = dict(BA=c[2], BnA=c[3], K=c[4], Ac=c[5], act=c[6])
        elif pr and len(c) == 9 and c[0] in MONS:
            out.setdefault((pr, c[0], "fam"), c[1:])
    return out


def wauroc(W, pc, ps, nc, ns, k):
    """Weighted AUROC (exact, as analyze.Boot.auroc_parts) for arbitrary unit weights W (nboot x k)."""
    cmp = (ps[:, None] > ns[None, :]) + 0.5 * (ps[:, None] == ns[None, :])
    M = np.zeros((k, k))
    np.add.at(M, (pc[:, None].repeat(len(nc), 1), nc[None, :].repeat(len(pc), 0)), cmp)
    npos = np.bincount(pc, minlength=k).astype(float); nneg = np.bincount(nc, minlength=k).astype(float)
    num = np.einsum("bi,ij,bj->b", W, M, W)
    den = (W @ npos) * (W @ nneg)
    with np.errstate(invalid="ignore", divide="ignore"):
        boot = np.where(den > 0, num / den, np.nan)
    return float(M.sum() / (npos.sum() * nneg.sum())), boot


def strat_weights(strata, seed=SEED, nboot=NBOOT):
    """Instance-level bootstrap weights, resampling instances within each stratum (family)."""
    rng = np.random.default_rng(seed)
    n = len(strata)
    W = np.zeros((nboot, n))
    groups = {}
    for i, s in enumerate(strata):
        groups.setdefault(s, []).append(i)
    for s in sorted(groups):
        ix = np.array(groups[s])
        draws = rng.integers(0, len(ix), size=(nboot, len(ix)))
        for b in range(nboot):
            W[b, ix] += np.bincount(draws[b], minlength=len(ix))
    return W


def f3(pt, bt, nd=3):
    if pt != pt:
        return "n/a"
    lo, hi = ci(bt)
    return f"{pt:.{nd}f} [{lo:.{nd}f}, {hi:.{nd}f}]"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--split", default="test")
    a = ap.parse_args()
    I = load_instances(a.split)
    insts = sorted({(r["inst"], r["family"], r["p"]) for r in I})
    ids = [i for i, _, _ in insts]
    fam = {i: f for i, f, _ in insts}
    sk = {i: skel(p) for i, _, p in insts}
    idx = {i: int(i.rsplit("-", 1)[-1]) for i in ids}
    par = {i: idx[i] % 2 for i in ids}
    fams = sorted(set(fam.values()))
    a1text = {r["inst"]: r["action"] for r in I if r["view"] == "action" and r["cond"] == "a1"}
    a0text = {r["inst"]: r["action"] for r in I if r["view"] == "action" and r["cond"] == "a0"}

    skB = Boot({sk[i] for i in ids})  # same construction as analyze.py -> identical weights
    K_CL = len(skB.clusters)
    cl_of = np.array([skB.idx[sk[i]] for i in ids])
    Wst = strat_weights([fam[i] for i in ids])  # instance-within-family bootstrap
    inst_ix = np.arange(len(ids))

    # sanity: skeleton == index mod 12
    assert all(int(sk[i][1:]) == idx[i] % 12 for i in ids), "skeleton != index mod 12"

    L = [f"# Post-hoc referee round 2 ({a.split}) — exploratory, not pre-registered", "",
         f"Generated by `HF_HUB_OFFLINE=1 OMP_NUM_THREADS=4 .venv/bin/python -I src/posthoc2.py --split {a.split}` "
         f"(python {sys.version.split()[0]}, numpy {np.__version__}). No model scoring; reads results/scores_{a.split}_*.jsonl.",
         f"Instances: {len(ids)} ({', '.join(f'{f} {sum(fam[i]==f for i in ids)}' for f in fams)}). "
         f"Skeleton clusters: **{K_CL}** (skeleton id p = instance index mod 12, verified for all instances). "
         f"Bootstraps: {NBOOT} resamples, numpy default_rng({SEED}); 95% percentile CIs.", ""]

    # ---------- section 3a: alias table (data only) ----------
    alias = ["## Skeleton / hack-variant alias", "",
             "| skeleton p | hack variant parity(s) | n instances | instance indices |", "|---|---|---|---|"]
    for c in skB.clusters:
        m = [i for i in ids if sk[i] == c]
        alias.append(f"| {c} | {sorted({par[i] for i in m})} | {len(m)} | {sorted({idx[i] for i in m})} |")
    cnt = Counter(sk[i] for i in ids)
    fixed = all(len({par[i] for i in ids if sk[i] == c}) == 1 for c in skB.clusters)
    alias += ["", f"Skeleton fixes the hack variant: **{fixed}** (parity = p mod 2 because 12 is even). "
                  f"Instances per skeleton: p00-p07 = {sorted({cnt[c] for c in skB.clusters[:8]})}, p08-p11 = {sorted({cnt[c] for c in skB.clusters[8:]})} "
                  f"(each family has indices 0-19, so p00-p07 get 2 per family and p08-p11 get 1 per family). "
                  f"Referee claim check: 'skeleton fixes the variant' = {fixed}; 'p00-p07 have 20 instances vs p08-p11 fewer': "
                  f"direction correct (p08-p11 fewer), but the counts are {cnt[skB.clusters[0]]} vs {cnt[skB.clusters[-1]]} per skeleton "
                  f"(20 is the number of instances per family, not per skeleton).", ""]

    # ---------- cue-stem exclusion list ----------
    cue_hit = {i: find_cues(a1text[i]) for i in ids}
    cue_hit0 = {i: find_cues(a0text[i]) for i in ids}
    excl = [i for i in ids if cue_hit[i]]
    keep = [i for i in ids if not cue_hit[i]]

    S1, S2, S3, S4, checks = [], [], [], [], []
    PH = parse_posthoc(os.path.join(ROOT, "results", f"posthoc_{a.split}.md"))
    for pr in PROMPTS:
        S = load_scores(a.split, pr)
        for m in MON_OF[pr]:
            if m not in S:
                checks.append(f"- {pr} {m}: no score file")
                continue
            s = S[m]
            if not all((i, v, c) in s for i in ids for v, cs in (("cot", ("A", "B", "Bnc", "Acue")), ("action", ("a0", "a1"))) for c in cs):
                checks.append(f"- {pr} {m}: incomplete score file ({len(s)} rows), skipped")
                continue
            g = lambda v, c: np.array([s[(i, v, c)]["score"] for i in ids])
            A, B, Bn, Ac = g("cot", "A"), g("cot", "B"), g("cot", "Bnc"), g("cot", "Acue")
            a0, a1 = g("action", "a0"), g("action", "a1")

            # ---- 1. cot view, skeleton cluster bootstrap ----
            def sk_au(pos, neg, sel=None):
                sel = np.arange(len(ids)) if sel is None else np.asarray(sel)
                return wauroc(skB.W, cl_of[sel], pos[sel], cl_of[sel], neg[sel], K_CL)
            pB, bB = sk_au(B, A); pN, bN = sk_au(Bn, A); pC, bC = sk_au(Ac, A)
            pK, bK = pB - pN, bB - bN
            # exact cluster sign-flip permutation: swap B/Bnc labels within instance, jointly per skeleton cluster
            n = len(ids)
            cB = ((B[:, None] > A[None, :]) + 0.5 * (B[:, None] == A[None, :])).sum(1)
            cN = ((Bn[:, None] > A[None, :]) + 0.5 * (Bn[:, None] == A[None, :])).sum(1)
            d_cl = np.bincount(cl_of, weights=cB - cN, minlength=K_CL) / (n * n)
            assert abs(d_cl.sum() - pK) < 1e-12
            signs = np.array(list(itertools.product((1, -1), repeat=K_CL)))
            Kp = signs @ d_cl
            p2 = float(np.mean(np.abs(Kp) >= abs(pK) - 1e-12)); p1 = float(np.mean(Kp >= pK - 1e-12))
            S1.append(f"| {pr} | {m} | {f3(pB, bB)} | {f3(pN, bN)} | {f3(pK, bK)} | {p1:.4f} | {p2:.4f} | {f3(pC, bC)} |")

            # ---- 2. action view, instance-pair bootstrap stratified by family ----
            def st_au(sel):
                sel = np.asarray(sel)
                return wauroc(Wst, inst_ix[sel], a1[sel], inst_ix[sel], a0[sel], len(ids))
            row_all, row_keep = [], []
            for subset, row in ((ids, row_all), (keep, row_keep)):
                pos = {i: k for k, i in enumerate(ids)}
                sel = [pos[i] for i in subset]
                row.append(f3(*st_au(sel), nd=2))
                for f in fams:
                    sf = [pos[i] for i in subset if fam[i] == f]
                    row.append(f3(*st_au(sf), nd=2) + f" (n={len(sf)})" if subset is keep else f3(*st_au(sf), nd=2))
            S2.append(f"| {pr} | {m} | all | " + " | ".join(row_all) + " |")
            S2.append(f"| {pr} | {m} | no-cue a1 | " + " | ".join(row_keep) + " |")

            # ---- 3. hack-variant parity ----
            r3 = []
            for h in (0, 1):
                sel = np.array([k for k, i in enumerate(ids) if par[i] == h])
                r3.append(f3(*st_au(sel), nd=2))
                r3.append(f3(*wauroc(skB.W, cl_of[sel], a1[sel], cl_of[sel], a0[sel], K_CL), nd=2))
            for h in (0, 1):  # cot B-vs-A per parity, skeleton bootstrap
                sel = np.array([k for k, i in enumerate(ids) if par[i] == h])
                r3.append(f3(*sk_au(B, A, sel), nd=2))
            S3.append(f"| {pr} | {m} | " + " | ".join(r3) + " |")

            # ---- 4. O per family ----
            if all((i, "both", c) in s for i in ids for c in ("A", "D")):
                bD, bA = g("both", "D"), g("both", "A")
                r4 = []
                for f in ["(pooled)"] + fams:
                    sel = np.arange(n) if f == "(pooled)" else np.array([k for k, i in enumerate(ids) if fam[i] == f])
                    pa, ba = wauroc(skB.W, cl_of[sel], a1[sel], cl_of[sel], a0[sel], K_CL)
                    pb, bb = wauroc(skB.W, cl_of[sel], bD[sel], cl_of[sel], bA[sel], K_CL)
                    qa, qa_b = wauroc(Wst, inst_ix[sel], a1[sel], inst_ix[sel], a0[sel], n)
                    qb, qb_b = wauroc(Wst, inst_ix[sel], bD[sel], inst_ix[sel], bA[sel], n)
                    assert abs((pa - pb) - (qa - qb)) < 1e-12
                    r4.append((f, pa, pb, f3(pa - pb, ba - bb), f3(qa - qb, qa_b - qb_b)))
                for f, pa, pb, o_sk, o_in in r4:
                    S4.append(f"| {pr} | {m} | {f} | {pa:.3f} | {pb:.3f} | {o_sk} | {o_in} |")

            # ---- consistency with posthoc.py (point estimates recomputed with its exact formulas) ----
            ref = dict(BA=auroc(B, A), BnA=auroc(Bn, A), Ac=auroc(Ac, A), act=auroc(a1, a0))
            got = dict(BA=pB, BnA=pN, Ac=pC, act=st_au(np.arange(n))[0])
            bad = {k: (ref[k], got[k]) for k in ref if abs(ref[k] - got[k]) > 1e-12}
            r1 = PH.get((pr, m))
            if r1 is None:
                checks.append(f"- {pr} {m}: not in posthoc_{a.split}.md")
            else:
                mine = dict(BA=f"{pB:.3f}", BnA=f"{pN:.3f}", K=f"{pK:+.3f}", Ac=f"{pC:.3f}", act=f"{ref['act']:.3f}")
                famv = [f"{auroc(a1[[k for k, i in enumerate(ids) if fam[i] == f]], a0[[k for k, i in enumerate(ids) if fam[i] == f]]):.2f}" for f in fams]
                famv += [f"{auroc(a1[[k for k, i in enumerate(ids) if par[i] == h]], a0[[k for k, i in enumerate(ids) if par[i] == h]]):.2f}" for h in (0, 1)]
                mis = {k: (r1[k], mine[k]) for k in mine if r1[k] != mine[k]}
                if PH.get((pr, m, "fam")) != famv:
                    mis["family/parity row"] = (PH.get((pr, m, "fam")), famv)
                checks.append(f"- {pr} {m}: rounded values vs posthoc_{a.split}.md (main + family/parity tables): {'all match' if not mis else 'MISMATCH ' + str(mis)}")
            checks.append(f"- {pr} {m}: point estimates vs posthoc.py formulas: {'match' if not bad else 'MISMATCH ' + str(bad)}")

    L += ["## 1. cot view: B-vs-A, Bnc-vs-A, K = B-Bnc, Acue-vs-A (AUROC) — skeleton-cluster bootstrap (12 clusters)", "",
          "Permutation test for K: within each instance the B and Bnc labels are swapped, the swap is applied jointly to every "
          f"instance of a skeleton cluster, and all 2^{K_CL} = {2**K_CL} assignments are enumerated (exact; null = K symmetric about 0). "
          "p1 = one-sided P(K_perm >= K_obs), p2 = two-sided P(|K_perm| >= |K_obs|). Minimum attainable p1 = 1/4096. "
          "With 12 clusters the percentile bootstrap CI is likely anti-conservative; the permutation p is the few-cluster-valid check.", "",
          "| prompt | monitor | B-A cot | Bnc-A cot | K | K perm p1 | K perm p2 | Acue-A cot |", "|---|---|---|---|---|---|---|---|"] + S1
    L += ["", "## 2. action view AUROC(a1 vs a0)", "",
          "Bootstrap: resample instance pairs (a0,a1 together) within family, 2000 resamples, seed 0 (pooled = stratified by family; "
          "per-family columns use the same draws restricted to that family). a0 negatives only from the same group.", "",
          f"Cue-stem exclusion: {len(excl)} / {len(ids)} instances have a1 action text matching a CUE_STEMS stem "
          f"(by family: {dict(sorted(Counter(fam[i] for i in excl).items()))}; matched words: {dict(sorted(Counter(w for i in excl for w in cue_hit[i]).items()))}). "
          f"For reference, a0 action texts with a cue match: {sum(bool(v) for v in cue_hit0.values())}. 'no-cue a1' rows use the remaining {len(keep)} instances.", "",
          "| prompt | monitor | subset | pooled | " + " | ".join(fams) + " |", "|" + "---|" * (4 + len(fams))] + S2
    L += [""] + alias
    L += ["## 3. hack-variant (instance index parity) breakdown", "",
          "Action-view AUROC(a1 vs a0) within parity, with two CIs: instance-pair-within-family bootstrap, and skeleton-cluster bootstrap "
          "(each parity contains exactly 6 skeleton clusters, so variant is fully aliased with skeleton). Also cot B-vs-A within parity (skeleton bootstrap).", "",
          "| prompt | monitor | act var0 (inst boot) | act var0 (skel boot) | act var1 (inst boot) | act var1 (skel boot) | cot B-A var0 | cot B-A var1 |",
          "|---|---|---|---|---|---|---|---|"] + S3
    L += ["", "## 4. H4 O per family", "",
          "O = AUROC_action(D vs A) - AUROC_both(D vs A) as in analyze.py (action view of D/A = a1/a0 scores; both view = D/A rows), "
          "computed within each family (all cross-instance pairs inside the family). CIs: skeleton-cluster bootstrap "
          "(same weights as analyze.py; each family spans all 12 skeletons) and instance-within-family bootstrap. "
          "Pooled row should equal analysis_test.md O.", "",
          "| prompt | monitor | family | AUROC action D-A | AUROC both D-A | O [skeleton CI] | O [instance CI] |",
          "|---|---|---|---|---|---|---|"] + S4
    L += ["", "## Consistency checks", ""] + checks
    out = os.path.join(ROOT, "results", f"posthoc_{a.split}_r2.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
