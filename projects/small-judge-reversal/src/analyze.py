"""Analysis of raw sweep JSONs -> results/analysis.json + results/analysis.md. Run: python -I src/analyze.py"""
import json, os, sys, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from sjr import config as C, data as D
from sjr.metrics import pair_flags, summarize, reference_rows, bootstrap, paired_bootstrap_diff, content, CATS

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(HERE, "results")
MODELS = [m for m in C.MODELS if m != "Qwen3-4B"]  # 4B = single-resample positive control, see calibrated.py
rb = {r["id"]: r for r in D.load_rb()}

def load(model):
    """-> {pair_id: {(criterion, order): letter}}, mass list, resample-of-id"""
    J, mass, rs = {}, [], {}
    for s in (0, 1, 2):
        d = json.load(open(os.path.join(RES, f"raw_{model}_r{s}.json")))
        for r in d["records"]:
            J.setdefault(r["id"], {})[(r["criterion"], r["order"])] = r["letter"]
            rs[r["id"]] = s
            if r["criterion"] in ("better", "W1"): mass.append(r["mass_AB"])
    return J, mass, rs

def flags_for(J, ids, worse="W1"):
    return [pair_flags(J[i], worse) for i in ids if all(k in J[i] for k in [("better","cf"),("better","rf"),(worse,"cf"),(worse,"rf")])]

def length_ok(J, ids):
    """Fraction of pairs where the judge picks the longer response (by characters) in both orders."""
    ok = n = 0
    for i in ids:
        if ("length", "cf") not in J[i]: continue
        lc, lr = len(rb[i]["chosen"]), len(rb[i]["rejected"])
        if lc == lr: continue
        longer = "C" if lc > lr else "R"
        n += 1
        ok += content(J[i][("length","cf")], "cf") == longer and content(J[i][("length","rf")], "rf") == longer
    return ok / n if n else float("nan"), n

out = {"models": {}, "reference": reference_rows()}
F = {}
for m in MODELS:
    J, mass, rs = load(m)
    ids = sorted(J)
    sec = {i: D.SUB2SEC[rb[i]["subset"]] for i in ids}
    ids_r0 = [i for i in ids if rs[i] == 0]
    F[m] = {i: pair_flags(J[i]) for i in ids}
    o = {"n_pairs": len(ids), "mean_mass_AB": float(np.mean(mass)), "min_mass_AB": float(np.min(mass)),
         "frac_mass_lt_0.5": float(np.mean(np.array(mass) < 0.5)),
         "pooled": summarize([F[m][i] for i in ids]),
         "per_section": {s: summarize([F[m][i] for i in ids if sec[i] == s]) for s in C.SECTIONS},
         "w2_r0": summarize(flags_for(J, ids_r0, "W2")),
         "w2_r0_w1_same_pairs": summarize([F[m][i] for i in ids_r0]),
         "length_ctrl": dict(zip(("acc_longer_both_orders", "n"), length_ok(J, ids_r0))),
         "letter_A_share_all": None}
    lo, hi, _ = bootstrap([F[m][i] for i in ids], "pos_locked_share_of_noncr")
    o["h2_poslocked_share_ci95"] = [lo, hi]
    lo, hi, _ = bootstrap([F[m][i] for i in ids], "cond_flip_rate")
    o["cond_flip_ci95"] = [lo, hi]
    out["models"][m] = o
    out["models"][m]["_ids"] = ids
ids = out["models"][MODELS[0]]["_ids"]
for m in MODELS: assert out["models"][m].pop("_ids") == ids
h1 = {}
for fam, (s, b) in {"Qwen2.5": ("Qwen2.5-0.5B-Instruct", "Qwen2.5-1.5B-Instruct"), "Qwen3": ("Qwen3-0.6B", "Qwen3-1.7B")}.items():
    lo, hi, nb = paired_bootstrap_diff([F[s][i] for i in ids], [F[b][i] for i in ids], "cond_flip_rate", alpha=0.025)
    lo2, hi2, _ = paired_bootstrap_diff([F[s][i] for i in ids], [F[b][i] for i in ids], "uncond_flip_chance_norm", alpha=0.025)
    h1[fam] = {"small": s, "big": b, "cond_flip_small": out["models"][s]["pooled"]["cond_flip_rate"],
               "cond_flip_big": out["models"][b]["pooled"]["cond_flip_rate"],
               "n_cond_small": out["models"][s]["pooled"]["n_cond"], "n_cond_big": out["models"][b]["pooled"]["n_cond"],
               "diff_ci975": [lo, hi], "n_valid_boot": nb, "uncond_norm_diff_ci975": [lo2, hi2]}
out["h1"] = h1
json.dump(out, open(os.path.join(RES, "analysis.json"), "w"), indent=1)

f = lambda x: "nan" if x != x else f"{x:.3f}"
L = ["# Analysis (auto-generated by src/analyze.py; W1 primary; 300 pooled pairs)", "",
     "| model | n_cond | acc_better_poscons | cond_flip | uncond_flip | " + " | ".join("sh_" + c for c in CATS) + " | A/B mass |",
     "|---|" + "---|" * (4 + len(CATS) + 1)]
for m in MODELS:
    p = out["models"][m]["pooled"]
    L.append(f"| {m} | {p['n_cond']} | {f(p['acc_better_poscons'])} | {f(p['cond_flip_rate'])} | {f(p['uncond_flip_rate'])} | "
             + " | ".join(f(p["share_" + c]) for c in CATS) + f" | {out['models'][m]['mean_mass_AB']:.3f} |")
for k, p in out["reference"].items():
    L.append(f"| ref:{k} | {p['n_cond']} | {f(p['acc_better_poscons'])} | {f(p['cond_flip_rate'])} | {f(p['uncond_flip_rate'])} | "
             + " | ".join(f(p["share_" + c]) for c in CATS) + " | - |")
L += ["", "## H1 (cond. flip rate, big minus small, paired bootstrap 97.5% CI)"]
for fam, h in h1.items():
    L.append(f"- {fam}: {f(h['cond_flip_small'])} (n_cond {h['n_cond_small']}) -> {f(h['cond_flip_big'])} (n_cond {h['n_cond_big']}); diff CI {[round(x,3) for x in h['diff_ci975']]} (valid boots {h['n_valid_boot']}); chance-normalised uncond diff CI {[round(x,3) for x in h['uncond_norm_diff_ci975']]}")
L += ["", "## H2 (position-locked share among non-correct-reversal pairs, 95% CI)"]
for m in MODELS:
    o = out["models"][m]
    L.append(f"- {m}: {f(o['pooled']['pos_locked_share_of_noncr'])} CI [{o['h2_poslocked_share_ci95'][0]:.3f}, {o['h2_poslocked_share_ci95'][1]:.3f}] (n_noncr {o['pooled']['n_noncr']})")
L += ["", "## Per section (n, acc_better_poscons, cond_flip(n_cond), share_pos_locked, share_criterion_blind, share_correct_reversal)"]
for m in MODELS:
    for s, p in out["models"][m]["per_section"].items():
        L.append(f"- {m} / {s}: n={p['n']}, acc={f(p['acc_better_poscons'])}, cond_flip={f(p['cond_flip_rate'])} (n_cond {p['n_cond']}), pl={f(p['share_position_locked'])}, cb={f(p['share_criterion_blind'])}, cr={f(p['share_correct_reversal'])}")
L += ["", "## Secondary: W2 wording vs W1 on resample 0 (100 pairs); length control (picks longer by chars, both orders, r0)"]
for m in MODELS:
    o = out["models"][m]
    L.append(f"- {m}: W1 cond_flip {f(o['w2_r0_w1_same_pairs']['cond_flip_rate'])}, W2 cond_flip {f(o['w2_r0']['cond_flip_rate'])} (n_cond {o['w2_r0']['n_cond']}); W1 cr share {f(o['w2_r0_w1_same_pairs']['share_correct_reversal'])}, W2 cr share {f(o['w2_r0']['share_correct_reversal'])}; length acc {f(o['length_ctrl']['acc_longer_both_orders'])} (n {o['length_ctrl']['n']})")
open(os.path.join(RES, "analysis.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
