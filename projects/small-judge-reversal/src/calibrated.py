"""Letter-prior-calibrated re-analysis (referee fix 1,2,4). Run: python -I src/calibrated.py
-> results/calibrated.json/.md + results/calibrated_null.json (compact null/diff table for the paper).
d_c = (score_cf - score_rf)/2 : >0 means judge prefers the chosen response, letter offset removed.

Independence null for calibrated reversal: null = P(d_better>0) * P(d_W1<0) (the reversal share expected if the
judge's calibrated verdicts under the two questions were independent, at the observed marginals). diff = reverse_cal
- null. Bootstrap: ONE index matrix (B=2000 draws of n pairs) per (model, subset), generated by
np.random.default_rng([SEED, crc32(model|subset)]) and reused for every CI in that row (corr, same_sign,
reverse_cal, null, diff), so all CIs in a row are computed on identical resamples (2.5/97.5 percentiles).
Rows: main eval pairs (raw_<model>_r<k>.json; subsets all/non-hep/hep/mass>0.9) and, when present, the new
non-code pair set (raw_nc_<model>_r<k>.json; subset label 'noncode-new', see src/run.py --pairs noncode)."""
import json, os, zlib
import numpy as np
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(HERE, "results")
MODELS = ["Qwen2.5-0.5B-Instruct", "Qwen2.5-1.5B-Instruct", "Qwen3-0.6B", "Qwen3-1.7B", "Qwen3-4B"]  # 4B = positive control, resample 1 only
SEED, B = 0, 2000
KEYS = [("better", "cf"), ("better", "rf"), ("W1", "cf"), ("W1", "rf")]


def load(m, prefix="raw"):
    R = {}
    for s in (0, 1, 2):
        fp = f"{RES}/{prefix}_{m}_r{s}.json"
        if not os.path.exists(fp): continue
        for r in json.load(open(fp))["records"]:
            R.setdefault(r["id"], {})[(r["criterion"], r["order"])] = r
    return R


def draws(m, name, n):
    rng = np.random.default_rng([SEED, zlib.crc32(f"{m}|{name}".encode())])
    return rng.integers(0, n, (B, n))


def stats(b, w):
    pb, pw = np.mean(b > 0), np.mean(w < 0)
    rv = np.mean((b > 0) & (w < 0))
    c = np.corrcoef(b, w)[0, 1] if np.std(b) > 0 and np.std(w) > 0 else np.nan
    return {"corr": c, "same_sign": np.mean(np.sign(b) == np.sign(w)), "acc_cal": pb, "p_W1_neg": pw,
            "reverse_cal": rv, "null_indep": pb * pw, "diff_vs_null": rv - pb * pw}


def row(m, name, b, w, pa):
    n = len(b)
    pt = stats(b, w)
    bs = [stats(b[ix], w[ix]) for ix in draws(m, name, n)]
    r = {"n": n, "pA": pa}
    for k, v in pt.items(): r[k] = float(v)
    for k in ("corr", "same_sign", "reverse_cal", "null_indep", "diff_vs_null"):
        v = np.array([x[k] for x in bs], float)
        r[k + "_ci"] = [float(np.nanpercentile(v, 2.5)), float(np.nanpercentile(v, 97.5))]
    dv = np.array([x["diff_vs_null"] for x in bs])
    r["diff_boot_share_le0"] = float(np.mean(dv <= 0))
    r["boot"] = {"B": B, "seed": [SEED, zlib.crc32(f"{m}|{name}".encode())], "shared_draws": True}
    return r


def arrays(R):
    ids = sorted(i for i in R if all(k in R[i] for k in KEYS))
    db = np.array([(R[i][("better", "cf")]["score"] - R[i][("better", "rf")]["score"]) / 2 for i in ids])
    dw = np.array([(R[i][("W1", "cf")]["score"] - R[i][("W1", "rf")]["score"]) / 2 for i in ids])
    mass = np.array([min(R[i][k]["mass_AB"] for k in KEYS) for i in ids])
    sub = [str(R[i][("better", "cf")]["subset"]) for i in ids]
    pa = {c: float(np.mean([R[i][(c, o)]["letter"] == "A" for i in ids for o in ("cf", "rf")])) for c in ("better", "W1")}
    return ids, db, dw, mass, sub, pa


f2 = lambda x: "nan" if x != x else f"{x:.2f}"
ci = lambda c: f"[{f2(c[0])},{f2(c[1])}]"
out, nullj = {}, {"definition": "null_indep = P(d_better>0)*P(d_W1<0); diff = reverse_cal - null_indep; 95% CIs from "
                  "one shared bootstrap draw per (model,subset), B=2000, seed [0, crc32('model|subset')]", "rows": {}}
L = ["# Calibrated re-analysis (letter offset removed)", "",
     "d = (score_cf - score_rf)/2 per criterion; `better` vs `W1`. corr = Pearson(d_better,d_W1); same_sign = share with sign(d_better)==sign(d_W1) (criterion-blind if high; reversal if ~0); acc_cal = share with d_better>0; reverse_cal = share with d_better>0 & d_W1<0; null = P(d_better>0)*P(d_W1<0) (independence null); diff = reverse_cal - null. Hep = HumanEvalPack ids (hep-*); noncode-new = separate 200-pair non-code set (src/run.py --pairs noncode). CI = bootstrap over pairs, 95%, B=2000; one shared index draw per (model, subset) used for every CI in the row.", "",
     "| model | subset | n | corr(better,W1) [CI] | same_sign [CI] | acc_cal(better) | reverse_cal [CI] | null [CI] | reverse-null [CI] | P(letter A) better/W1 |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for m in MODELS:
    for prefix, rows in (("raw", None), ("raw_nc", "noncode-new")):
        R = load(m, prefix)
        if not R: continue
        ids, db, dw, mass, sub, pa = arrays(R)
        isH = np.array([s.startswith("hep") for s in sub])
        if rows is None:
            masks = [("all", np.ones(len(ids), bool)), ("non-hep", ~isH), ("hep", isH), ("mass>0.9 all 4 passes", mass > 0.9)]
        else:
            masks = [("noncode-new", np.ones(len(ids), bool)), ("noncode-new mass>0.9 all 4 passes", mass > 0.9)]
        for name, mk in masks:
            b, w = db[mk], dw[mk]
            if len(b) < 10: continue
            r = row(m, name, b, w, pa)
            out.setdefault(m, {})[name] = r
            nullj["rows"].setdefault(m, {})[name] = {k: (round(r[k], 4) if isinstance(r[k], float) else r[k]) for k in
                ("n", "acc_cal", "p_W1_neg", "reverse_cal", "reverse_cal_ci", "null_indep", "null_indep_ci",
                 "diff_vs_null", "diff_vs_null_ci", "diff_boot_share_le0")}
            for k in ("reverse_cal_ci", "null_indep_ci", "diff_vs_null_ci"):
                nullj["rows"][m][name][k] = [round(x, 4) for x in r[k]]
            L.append(f"| {m} | {name} | {r['n']} | {f2(r['corr'])} {ci(r['corr_ci'])} | {f2(r['same_sign'])} {ci(r['same_sign_ci'])} | "
                     f"{f2(r['acc_cal'])} | {f2(r['reverse_cal'])} {ci(r['reverse_cal_ci'])} | {f2(r['null_indep'])} {ci(r['null_indep_ci'])} | "
                     f"{f2(r['diff_vs_null'])} {ci(r['diff_vs_null_ci'])} | {pa['better']:.2f}/{pa['W1']:.2f} |")
        if rows is not None: continue
        # letter-biased null: independent letters at observed per-criterion rates (main pairs only)
        pb = float(np.mean([R[i][("better", o)]["letter"] == "A" for i in ids for o in ("cf", "rf")]))
        pw = float(np.mean([R[i][("W1", o)]["letter"] == "A" for i in ids for o in ("cf", "rf")]))
        obs = np.mean([len({R[i][k]["letter"] for k in KEYS}) == 1 for i in ids])
        exp = pb**2 * pw**2 + (1 - pb)**2 * (1 - pw)**2
        out[m]["letter_null"] = {"pA_better": pb, "pA_W1": pw, "all_four_same_letter_expected": float(exp), "observed": float(obs),
                                 "pos_consistent_acc_expected_better": float(pb * (1 - pb))}
        L.append(f"| {m} | letter-null (all four passes same letter) | {len(ids)} | expected {exp:.2f} | observed {obs:.2f} | | | | | |")
json.dump(out, open(f"{RES}/calibrated.json", "w"), indent=1)
json.dump(nullj, open(f"{RES}/calibrated_null.json", "w"), indent=1)
open(f"{RES}/calibrated.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
