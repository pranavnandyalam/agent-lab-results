"""Count parameters of cached models from safetensors headers only (no weights loaded, no download).
Run: python -I src/param_count.py [--write] [model ...]  -> prints JSON {model: {...}}; default: all models in
sjr.config.MODELS (None if not cached). --write also stores the counts in results/models.json ("params", "Qwen3-4B")
and a generated section of results/models.md (between PARAMS markers). n_params counts tied embeddings once (a stored lm_head copy is dropped); n_params_stored = all stored tensors."""
import json, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sjr import config as C


def snapshot_dir(repo, rev):
    return os.path.join(C.HF_HOME, "hub", "models--" + repo.replace("/", "--"), "snapshots", rev)


def count(name):
    repo, rev = C.MODELS[name]
    d = snapshot_dir(repo, rev)
    if not os.path.isdir(d): return None
    files = sorted(f for f in os.listdir(d) if f.endswith(".safetensors"))
    n, dtypes, nbytes, lm_head = 0, set(), 0, 0
    for f in files:
        with open(os.path.join(d, f), "rb") as fh:
            (hl,) = struct.unpack("<Q", fh.read(8))
            hdr = json.loads(fh.read(hl))
        for k, v in hdr.items():
            if k == "__metadata__": continue
            p = 1
            for s in v["shape"]: p *= s
            if k == "lm_head.weight": lm_head = p
            n += p; dtypes.add(v["dtype"]); nbytes += v["data_offsets"][1] - v["data_offsets"][0]
    cfg = json.load(open(os.path.join(d, "config.json")))
    emb = cfg["vocab_size"] * cfg["hidden_size"]
    uniq = n - lm_head if cfg.get("tie_word_embeddings") else n  # tied lm_head stored as a copy: count once
    return {"repo": repo, "revision": rev, "n_params_stored": n, "lm_head_stored": lm_head > 0,
            "n_params": uniq, "n_params_non_embedding": uniq - emb * (1 if cfg.get("tie_word_embeddings") else 2),
            "tie_word_embeddings": cfg.get("tie_word_embeddings"), "safetensors_dtypes": sorted(dtypes),
            "safetensors_bytes": nbytes, "n_shards": len(files)}


RES = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
B0, B1 = "<!-- PARAMS:BEGIN (generated by src/param_count.py --write) -->", "<!-- PARAMS:END -->"


def write(P):
    jp, mp = os.path.join(RES, "models.json"), os.path.join(RES, "models.md")
    J = json.load(open(jp))
    J["params"] = {m: v for m, v in P.items() if v}
    if P.get("Qwen3-4B"):  # optional positive-control judge (fetched only with FETCH_4B=1)
        J.setdefault("optional_models", {})["Qwen/Qwen3-4B"] = C.MODELS["Qwen3-4B"][1]
    json.dump(J, open(jp, "w"), indent=1)
    md = open(mp).read()
    if B0 in md: md = md[:md.index(B0)].rstrip("\n") + "\n" + md[md.index(B1) + len(B1):].lstrip("\n")
    rows = [B0, "", "## Parameter counts (from cached safetensors headers; tied embeddings counted once)", "",
            "| model | revision | params | non-embedding | stored tensors (incl. lm_head copy) | bf16 bytes |",
            "|---|---|---|---|---|---|"]
    for m, v in P.items():
        if v: rows.append(f"| {m} | {v['revision'][:10]} | {v['n_params']:,} | {v['n_params_non_embedding']:,} | "
                          f"{v['n_params_stored']:,} | {v['safetensors_bytes']:,} |")
    rows += ["", B1]
    open(mp, "w").write(md.rstrip("\n") + "\n\n" + "\n".join(rows) + "\n")


if __name__ == "__main__":
    args = sys.argv[1:]
    w = "--write" in args
    names = [a for a in args if a != "--write"] or list(C.MODELS)
    P = {m: count(m) for m in names}
    print(json.dumps(P, indent=1))
    if w: write(P)
